def chapter_curriculum(subject, number):
    offset = 1 if subject == "C_program" else 0
    prerequisites, *objectives = CURRICULUM[subject][number - offset]
    return dict(
        objectives=[
            dict(id=f"{subject}_{number:02d}:objective:{i+1}", text=text)
            for i, text in enumerate(objectives)
        ],
        prerequisite_ids=[f"{subject}_{n:02d}" for n in prerequisites],
    )


def prerequisite_chain(subject, number):
    ordered = []

    def visit(current):
        for key in chapter_curriculum(subject, current)["prerequisite_ids"]:
            visit(int(key.rsplit("_", 1)[1]))
            if key not in ordered:
                ordered.append(key)

    visit(number)
    return ordered
